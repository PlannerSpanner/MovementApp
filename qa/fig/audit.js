// The figure audit, as a gauntlet step. For every in-scope movement (Morning Flow, Daily 13,
// Strength) it runs (a) the executable rubric lines in rubric.js and (b) the numeric checks in
// checks.js, on the real engine + data from src/.
//   A failing line is a build failure unless it is listed in todo.json (known fault, fix pending)
//   or, for the judgement flags only, in waivers.json with a written reason.
//   A todo or waiver that no longer fires is ALSO a failure: the lists must stay true.
//   node qa/fig/audit.js             check (exit 1 on any failure)
//   node qa/fig/audit.js --init      write todo.json from the current failures (bootstrap only)
//   node qa/fig/audit.js --verbose   print every line, passing or not
//   node qa/fig/audit.js --only=str  one movement (report only, exit 0)
// Full report: qa/screenshots/fig/audit.md
const fs=require('fs'),path=require('path');
const {load,IN_SCOPE}=require('./engine'),{audit,HARD}=require('./checks'),{RUBRIC,LOOK}=require('./rubric');
const {sample}=require('./lib');
const TODO_F=path.join(__dirname,'todo.json'),WAIVE_F=path.join(__dirname,'waivers.json');
const rdj=(f,d)=>fs.existsSync(f)?JSON.parse(fs.readFileSync(f,'utf8')):d;
const args=process.argv.slice(2),init=args.includes('--init'),verbose=args.includes('--verbose');
const only=(args.find(a=>a.startsWith('--only='))||'').slice(7).toLowerCase();
const todo=new Set(rdj(TODO_F,[])),waive=rdj(WAIVE_F,{});
const seen=new Set(),fails=[],todos=[],waived=[],md=['# Figure audit','','Generated by `node qa/fig/audit.js` from `src/`. 64 phases per movement.',''];
let nRub=0,nRubPass=0,nLook=0,nFlag=0;
for(const app of IN_SCOPE){
  const E=load(app); md.push('## '+E.label,'');
  const R=RUBRIC[app]||{};
  for(const n of Object.keys(R))if(!E.MOVES.find(m=>m.n===n)){fails.push(`${app}/${n}: rubric names a movement that does not exist`);}
  E.MOVES.forEach((m,mi)=>{
    if(only&&!m.n.toLowerCase().includes(only))return;
    const key=`${app}/${m.n}`, lines=R[m.n];
    md.push(`**${mi+1}. ${m.n}** (scale ${m.fit.sc.toFixed(2)})`);
    if(!lines){fails.push(`${key}: no rubric assertions`);return;}
    const C=sample(E,m);
    const rec=(id,pass,text,detail,judgement)=>{
      const full=`${key}#${id}`; seen.add(full);
      if(pass){ if(todo.has(full))fails.push(`${full}: listed in todo.json but passes now (remove it)`);
        if(waive[full])fails.push(`${full}: waived in waivers.json but no longer fires (remove it)`);
        if(verbose||only)console.log(`  ok    ${full}  ${text}`); md.push(`- ok \`${id}\` ${text}`); return; }
      const line=`${full}  ${text}${detail?' -- '+detail:''}`;
      if(judgement&&waive[full]){waived.push(line);md.push(`- waived \`${id}\` ${text}: ${detail}. Reason: ${waive[full]}`);}
      else if(todo.has(full)){todos.push(line);md.push(`- TODO \`${id}\` ${text}: ${detail}`);}
      else{fails.push(line);md.push(`- **FAIL** \`${id}\` ${text}: ${detail}`);}
    };
    for(const [id,text,fn] of lines){nRub++;let r;try{r=fn(C);}catch(e){r='assertion threw: '+e.message;}
      if(r===true)nRubPass++; rec(id,r===true,text,r===true?'':String(r),false);}
    const look=(LOOK[app]||{})[m.n]||[]; nLook+=look.length;
    if(look.length)md.push(`- look \`${look.join('`, `')}\` judged on the phase sheet, not executable`);
    const A=audit(E,m); const fired=new Set(A.flags.map(f=>f.id));
    A.flags.forEach(f=>{nFlag++;rec(f.id,false,f.k,f.msg,!HARD.includes(f.k));});
    // todo / waiver entries for numeric flags that did not fire
    [...todo,...Object.keys(waive)].filter(t=>t.startsWith(key+'#')&&/#[a-zA-Z]+:/.test(t)&&!fired.has(t.split('#')[1]))
      .forEach(t=>fails.push(`${t}: listed in ${todo.has(t)?'todo.json':'waivers.json'} but no longer fires (remove it)`));
    md.push('');
  });
}
if(!only)[...todo,...Object.keys(waive)].forEach(t=>{if(!seen.has(t)&&!/#[a-zA-Z]+:/.test(t))fails.push(`${t}: listed but no such assertion exists`);});
if(init){const cur=[...new Set([...fails.filter(l=>/^[^:]+#\S+  /.test(l)).map(l=>l.split('  ')[0]),...todos.map(l=>l.split('  ')[0])])].sort();
  fs.writeFileSync(TODO_F,JSON.stringify(cur,null,1)+'\n');console.log(`todo.json written: ${cur.length} known faults`);process.exit(0);}
if(only){todos.forEach(l=>console.log('  todo  '+l));waived.forEach(l=>console.log('  waive '+l));fails.forEach(l=>console.log('  FAIL  '+l));process.exit(0);}
const O=path.join(__dirname,'..','screenshots','fig');fs.mkdirSync(O,{recursive:true});
md.splice(3,0,`Rubric lines: ${nRub} executable (${nRubPass} pass), ${nLook} judged by eye. Numeric flags: ${nFlag}. Known faults pending (todo.json): ${todos.length}. Waived with a reason: ${waived.length}. Failures: ${fails.length}.`,'');
fs.writeFileSync(path.join(O,'audit.md'),md.join('\n'));
if(verbose)todos.forEach(l=>console.log('  todo  '+l));
fails.forEach(l=>console.log('  FAIL  '+l));
console.log(`figure audit: ${nRub} executable rubric lines (${nRubPass} pass), ${nLook} look-only, ${nFlag} numeric flags; ${todos.length} known faults pending, ${waived.length} waived, ${fails.length} failures`);
console.log(fails.length?'FIGURE AUDIT FAIL':'FIGURE AUDIT PASS');
process.exit(fails.length?1:0);
