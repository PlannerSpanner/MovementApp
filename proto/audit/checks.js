// Numeric audit of the CURRENT engine's poses, on the real engine + data (see engine.js).
// These are checks the shipped QA does not have. Every movement is sampled at 64 phases.
//   node proto/audit/checks.js [--json]   -> proto/audit/out/checks.md (+ checks.json)
// Checks (all in engine units; the figure is ~80 units tall, so 1 unit ~ 2.2 cm):
//  floor      a joint below the floor plane (y > 93.6)
//  miss       an IK hand/foot target the limb cannot reach (effector > 0.5 from its target)
//  kneeBack   knee bending the wrong way relative to the pelvis' own front (review flag)
//  hyperExt   hip extension beyond 35 deg / flexion beyond 135 / abduction beyond 60 (review flag)
//  hidden     a limb segment that is fully covered by the torso on screen AND behind it
//  merged     left and right of the same limb drawn on top of each other (< 1.6 screen units apart end to end)
//  short      a limb that MOVES during the cycle but is foreshortened below 35% of its true length
//             at some phase (it points into or out of the lens)
//  pop        a joint that jumps: one 1/64 step more than 5x its own median step and > 2.5 units
//  small      on-screen figure scale: how many screen units (of 100) one limb segment gets
const fs=require('fs'),path=require('path');
const {load,APPS}=require('./engine');
const N=64, FLOOR=93;
const sub=(a,b)=>[a[0]-b[0],a[1]-b[1],a[2]-b[2]], dot=(a,b)=>a[0]*b[0]+a[1]*b[1]+a[2]*b[2];
const len=v=>Math.hypot(v[0],v[1],v[2]), nrm=v=>{const n=len(v)||1;return v.map(x=>x/n);};
const cross=(a,b)=>[a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0]];
const deg=r=>r*180/Math.PI, ang=(a,b)=>deg(Math.acos(Math.max(-1,Math.min(1,dot(nrm(a),nrm(b))))));
const SEG=[['shL','elL'],['elL','haL'],['shR','elR'],['elR','haR'],['hpL','knL'],['knL','ftL'],['hpR','knR'],['knR','ftR']];
const inPoly=(p,poly)=>{let c=false;for(let i=0,j=poly.length-1;i<poly.length;j=i++){
  const a=poly[i],b=poly[j]; if((a.y>p.y)!==(b.y>p.y)&&p.x<(b.x-a.x)*(p.y-a.y)/(b.y-a.y)+a.x)c=!c;}return c;};
const out={}, lines=['# Numeric audit of the current engine','',
  'Generated by `node proto/audit/checks.js` from the shipped `src/` engine and data. 64 phases per movement.',
  'Units: the figure is about 80 units tall, so 1 unit is roughly 2.2 cm. Phases listed are where the fault peaks.',''];
for(const app of Object.keys(APPS)){
  const E=load(app); lines.push('## '+E.label,'');
  E.MOVES.forEach((m,mi)=>{
    const F=[]; const add=(k,msg)=>F.push({k,msg});
    E.setCam(m);
    const fr=[]; for(let i=0;i<N;i++){const ph=i/N,pose=E.poseAt(m,ph),j=E.solve(pose);fr.push({ph,pose,j});}
    const worst=(fn)=>{let b=null;fr.forEach(f=>{const v=fn(f);if(v!=null&&(b==null||v.v>b.v))b=Object.assign({ph:f.ph},v);});return b;};
    // floor
    const fl={};fr.forEach(f=>{for(const k in f.j){const d=f.j[k][1]-FLOOR;if(d>0.6&&(!fl[k]||d>fl[k].d))fl[k]={d,ph:f.ph};}});
    for(const k in fl)add('floor',`${k} ${fl[k].d.toFixed(1)} below the floor at ph ${fl[k].ph.toFixed(2)}`);
    // IK miss
    [['ikL','haL'],['ikR','haR'],['ikFL','ftL'],['ikFR','ftR']].forEach(([t,jn])=>{
      const w=worst(f=>{let T=f.pose[t];if(!T)return null;T=Array.isArray(T)?T:(T.w||f.j[T.k]);if(!T)return null;return {v:len(sub(f.j[jn],T))};});
      if(w&&w.v>0.5)add('miss',`${jn} misses its ${t} target by ${w.v.toFixed(1)} at ph ${w.ph.toFixed(2)} (limb too short for the pose)`);});
    // knee direction + hip range, in the pelvis' own frame
    ['L','R'].forEach(s=>{
      const kb=worst(f=>{const j=f.j,lat=nrm(sub(j.hpR,j.hpL)),up=nrm(sub(j.chest,j.pelvis));
        const th=sub(j['kn'+s],j['hp'+s]),shn=sub(j['ft'+s],j['kn'+s]);
        const knee=180-ang(th,shn); if(knee>172)return null;
        // a knee flexes so that cross(thigh,shin) points along -lateral (y is down, forward is +z)
        const sgn=dot(cross(th,shn),lat); return sgn>0.15*len(th)*len(shn)?{v:180-knee}:null;});
      if(kb)add('kneeBack',`kn${s} flexed ${kb.v.toFixed(0)} deg with the bend plane reversed at ph ${kb.ph.toFixed(2)} (check it is hip rotation, not a backward knee)`);
      const hx=worst(f=>{const j=f.j,up=nrm(sub(j.chest,j.pelvis)),lat=nrm(sub(j.hpR,j.hpL)),fw=nrm(cross(up,lat));
        const th=nrm(sub(j['kn'+s],j['hp'+s])); // neutral thigh = -up
        const ext=deg(Math.atan2(-dot(th,fw),-dot(th,up))); return ext>35?{v:ext}:null;});
      if(hx)add('hyperExt',`hp${s} extended ${hx.v.toFixed(0)} deg behind the trunk line at ph ${hx.ph.toFixed(2)} (anatomical limit ~20-30)`);
    });
    // hidden / merged / short on screen
    const scr=(f,k)=>{const q=E.project(f.j[k]);return {x:q.x*m.fit.sc+m.fit.ox,y:q.y*m.fit.sc+m.fit.oy,d:q.d};};
    SEG.forEach(([a,b])=>{
      const hid=fr.filter(f=>{const T=['shL','shR','hpR','hpL'].map(k=>scr(f,k)),A=scr(f,a),B=scr(f,b),M={x:(A.x+B.x)/2,y:(A.y+B.y)/2};
        const td=T.reduce((s,p)=>s+p.d,0)/4; return inPoly(B,T)&&inPoly(M,T)&&(A.d+B.d)/2<td;});
      if(hid.length>=N/8)add('hidden',`${a}-${b} is behind the torso and fully covered for ${(100*hid.length/N).toFixed(0)}% of the cycle (first at ph ${hid[0].ph.toFixed(2)})`);
      // moving?
      const d0=nrm(sub(fr[0].j[b],fr[0].j[a])); let sweep=0; fr.forEach(f=>{sweep=Math.max(sweep,ang(d0,sub(f.j[b],f.j[a])));});
      if(sweep>25){const w=worst(f=>{const A=scr(f,a),B=scr(f,b),tl=len(sub(f.j[b],f.j[a]))*m.fit.sc;return {v:1-Math.hypot(A.x-B.x,A.y-B.y)/tl};});
        if(w.v>0.65)add('short',`${a}-${b} sweeps ${sweep.toFixed(0)} deg but is foreshortened to ${(100*(1-w.v)).toFixed(0)}% of its length at ph ${w.ph.toFixed(2)}`);}
    });
    [['shL','elL','haL','shR','elR','haR','arms'],['hpL','knL','ftL','hpR','knR','ftR','legs']].forEach(([a,b,c,d,e,g,nm])=>{
      const mg=fr.filter(f=>[[b,e],[c,g]].every(([p,q])=>{const P=scr(f,p),Q=scr(f,q);return Math.hypot(P.x-Q.x,P.y-Q.y)<1.6*m.fit.sc;}));
      if(mg.length>=N/4)add('merged',`left and right ${nm} are drawn on top of each other for ${(100*mg.length/N).toFixed(0)}% of the cycle`);});
    // pops
    for(const k in fr[0].j){const st=fr.map((f,i)=>len(sub(fr[(i+1)%N].j[k],f.j[k])));
      const nz=st.filter(x=>x>1e-3).sort((x,y)=>x-y); if(!nz.length)continue; const med=nz[nz.length>>1];
      const mx=Math.max(...st), at=st.indexOf(mx);
      if(mx>2.5&&mx>5*med)add('pop',`${k} jumps ${mx.toFixed(1)} in one 1/64 step at ph ${fr[at].ph.toFixed(2)} (median step ${med.toFixed(2)})`);}
    add('small',`scale ${m.fit.sc.toFixed(2)}: a forearm is ${(13*m.fit.sc).toFixed(0)}% of the stage width, stroke ${(3*m.fit.sc).toFixed(1)}`);
    out[app+'/'+m.n]=F;
    const real=F.filter(f=>f.k!=='small');
    lines.push(`**${mi+1}. ${m.n}** (${F.find(f=>f.k==='small').msg})`);
    if(!real.length)lines.push('- no numeric flags'); else real.forEach(f=>lines.push(`- \`${f.k}\` ${f.msg}`));
    lines.push('');
  });
}
const O=path.join(__dirname,'out'); fs.mkdirSync(O,{recursive:true});
fs.writeFileSync(path.join(O,'checks.md'),lines.join('\n'));
fs.writeFileSync(path.join(O,'checks.json'),JSON.stringify(out,null,1));
